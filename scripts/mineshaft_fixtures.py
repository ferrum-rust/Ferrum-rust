"""Developer-only original-bytecode mineshaft differential fixture generator."""
import json
import os
from pathlib import Path
import subprocess
from vanilla_world import classpath

ROOT=Path(__file__).resolve().parents[1]
jar=Path(os.environ['APPDATA'])/'.minecraft/versions/1.8.9/1.8.9.jar'
classes=ROOT/'.local/mineshaft-oracle'
classes.mkdir(parents=True,exist_ok=True)
cp=classpath(jar)
subprocess.run(['javac','-encoding','UTF-8','-cp',cp,'-d',str(classes),str(ROOT/'tools/java/MineshaftOracle.java')],check=True)
result=subprocess.run(['java','-Xmx512M','-cp',str(classes)+os.pathsep+cp,'MineshaftOracle'],check=True,capture_output=True,text=True)
data=json.loads(result.stdout)
target=ROOT/'tests/fixtures/vanilla189-mineshafts.json'
target.write_text(json.dumps(data,separators=(',',':'))+'\n',encoding='utf-8')
native=['// Generated by scripts/mineshaft_fixtures.py from the owned original 1.8.9 registry.\n',
        'const ENCHANTMENTS: &[Enchantment] = &[\n']
for entry in data['enchantments']:
    ranges=', '.join(f'({lo}, {hi})' for lo,hi in entry['ranges'])
    incompatible=', '.join(map(str,entry['incompatible']))
    native.append(f'    Enchantment {{ id: {entry["id"]}, weight: {entry["weight"]}, ranges: &[{ranges}], incompatible: &[{incompatible}] }},\n')
native.append('];\n')
(ROOT/'src/vanilla/mineshaft_enchantments.rs').write_text(''.join(native),encoding='utf-8')
print(f'{len(data["cases"])} mineshaft layouts, {sum(len(r["pieces"]) for r in data["cases"])} pieces: {target}')
