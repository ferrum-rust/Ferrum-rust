"""Export original pick-item results, tile tags and InventoryPlayer.setCurrentItem transitions."""
import json
import os
from pathlib import Path
import subprocess
from vanilla_world import classpath, java_executable

ROOT = Path(__file__).resolve().parents[1]
out = ROOT / ".local/middle-pick-oracle"
out.mkdir(parents=True, exist_ok=True)
version = Path(os.environ["APPDATA"]) / ".minecraft/versions/1.8.9"
cp = classpath(version / "1.8.9.jar")
compiler = os.environ.get("MC189_JAVAC", r"C:\Program Files\Java\jdk1.8.0_202\bin\javac.exe")
subprocess.run([compiler,"-encoding","UTF-8","-cp",cp,"-d",str(out),
                *[str(ROOT/"tools/java"/(n+".java")) for n in ["MovementOracle","EntityPickOracle","MiddlePickOracle","TileUpdatesOracle"]]],check=True)
native = os.environ.get("MC189_LWJGL_NATIVES", str(version / "natives-windows-x86_64"))
region=ROOT/"tests/fixtures/middle-pick-import/region/r.-1.0.mca"
result=subprocess.run([java_executable(),"-Djava.awt.headless=true","-Dorg.lwjgl.librarypath="+native,
                       "-Xmx512M","-cp",str(out)+os.pathsep+cp,"MiddlePickOracle",str(region)],capture_output=True,text=True)
if result.returncode:
    print(result.stderr)
    result.check_returncode()
tile_updates=subprocess.run([java_executable(),"-Djava.awt.headless=true","-Dorg.lwjgl.librarypath="+native,
                             "-Xmx512M","-cp",str(out)+os.pathsep+cp,"TileUpdatesOracle"],capture_output=True,text=True)
if tile_updates.returncode:
    print(tile_updates.stderr)
    tile_updates.check_returncode()
updates=json.loads(tile_updates.stdout)
(ROOT/"tests/fixtures/vanilla189-tile-updates.json").write_text(json.dumps(updates,separators=(",",":"))+"\n",encoding="utf-8")
data=json.loads(result.stdout)
(ROOT/"tests/fixtures/vanilla189-middle-pick.json").write_text(json.dumps(data,separators=(",",":"))+"\n",encoding="utf-8")
print({k:len(v) for k,v in data.items()})
# End of fixture export also writes small lookup tables from the real client + item registry.
rows = [0] * 4096
for state,item,meta,subtypes in data['registry']:
    assert 0 <= meta < 256
    rows[state] = item << 9 | meta << 1 | int(subtypes)
text = "// Actual 1.8.9 pick results and tile-provider defaults. Generated by middle_pick_fixtures.py.\n"
text += "static BLOCK: [u32;4096] = [\n" + "".join(
    "    " + ", ".join(map(str, rows[i:i+32])) + ",\n" for i in range(0,4096,32)) + "];\n"
text += "const ITEM: &[(u16,&str,u8)] = &[\n" + "".join(
    f'    ({item}, {json.dumps(name)}, {int(subtype) | int(one)<<1 | int(two)<<2}),\n'
    for item,subtype,one,two,name in sorted(data["items"])) + "];\n"
text += "const ENTITY: &[(u8,u16,u16)] = &[\n" + "".join(
    f"    ({e},{stack[0]},{stack[2]}),\n" for e,stack in data["entities"] if stack) + "];\n"
seen = set()
tiles = []
for t in data["tiles"]:
    block = t["raw"] >> 4
    if block not in seen:
        seen.add(block)
        tiles.append((block,t["name"],t["tile"]))
text += "const TILE: &[(u16,&str,&str)] = &[\n" + "".join(
    f'    ({b}, {json.dumps(name)}, "{default}"),\n' for b,name,default in tiles) + "];\n"
(ROOT / "src/vanilla/middle_pick_data.rs").write_text(text,encoding="utf-8")
