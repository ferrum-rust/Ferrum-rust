"""Export actual 1.8.9 ground-path decisions and the passable-state lookup."""
import gzip
import json
import os
import subprocess
from pathlib import Path
from vanilla_world import ROOT, classpath, java_executable

cp = classpath(Path(os.environ["APPDATA"]) / ".minecraft/versions/1.8.9/1.8.9.jar")
out = ROOT / ".local/oracles/ground-paths"
out.mkdir(parents=True, exist_ok=True)
sources = [ROOT / "tools/java" / name for name in ("FallingEntityOracle.java", "GroundPathOracle.java", "GroundNavigationOracle.java", "MobMoveOracle.java")]
subprocess.run(["javac", "--release", "8", "-cp", cp, "-d", str(out), *map(str, sources)], check=True)
fixture = ROOT / "tests/fixtures/vanilla189-ground-paths.json.gz"
subprocess.run([java_executable(), "-Xmx512m", "-cp", str(out) + os.pathsep + cp, "GroundPathOracle",
                str(fixture)], cwd=ROOT, check=True)
rows = json.loads(gzip.decompress(fixture.read_bytes()))["passable"]
bits = [0] * 64
for state, passes in rows:
    if passes:
        bits[state // 64] |= 1 << (state % 64)
(ROOT / "src/mob_path_data.rs").write_text(
    "// Generated by scripts/test_vanilla_ground_paths.py from the original Block registry.\n"
    + "const PASSABLE: [u64; 64] = [\n"
    + "".join(f"    0x{entry:016x},\n" for entry in bits)
    + "];\n", encoding="utf-8")
subprocess.run([java_executable(), "-Xmx512m", "-cp", str(out) + os.pathsep + cp, "GroundNavigationOracle",
                str(ROOT / "tests/fixtures/vanilla189-ground-navigation.json.gz")], cwd=ROOT, check=True)
motion_fixture = ROOT / "tests/fixtures/vanilla189-mob-move.json.gz"
subprocess.run([java_executable(), "-Xmx512m", "-cp", str(out) + os.pathsep + cp, "MobMoveOracle",
                str(motion_fixture)], cwd=ROOT, check=True)
tables = json.loads(gzip.decompress(motion_fixture.read_bytes()))["tables"]
source = ["// Original MathHelper.atan2 asin/cos tables exported by test_vanilla_ground_paths.py."]
for name, values in zip(("ASIN", "COS"), tables):
    source.append(f"const {name}: [u64; 257] = [")
    source.extend(f"    0x{int(value, 16):016x}," for value in values)
    source.append("];")
(ROOT / "src/mob_angle_data.rs").write_text("\n".join(source) + "\n", encoding="utf-8")
